"""Video probing, frame sampling, scanning and engine handling. Uses the bundled ffmpeg."""
import csv
import shutil
import subprocess
from types import SimpleNamespace

import pytest

from image_cataloger.engines.api_engine import ApiEngine
from image_cataloger.engines.base import RunControl
from image_cataloger.engines.cli_engine import CliEngine
from image_cataloger.scanner import is_video_file, media_kind, scan_folder
from image_cataloger.video import VideoError, find_ffmpeg, probe_video, sample_frames

pytestmark = pytest.mark.skipif(find_ffmpeg() is None, reason="ffmpeg not available")


@pytest.fixture(scope="module")
def clip(tmp_path_factory):
    """A 3-second 160x120 test-pattern mp4 generated by ffmpeg."""
    path = tmp_path_factory.mktemp("vid") / "clip.mp4"
    subprocess.run(
        [find_ffmpeg(), "-v", "error", "-y", "-f", "lavfi", "-i", "testsrc=duration=3:size=160x120:rate=10",
         "-pix_fmt", "yuv420p", str(path)],
        check=True,
    )
    return str(path)


def test_scanner_recognises_videos(tmp_path):
    for name in ("a.MP4", "b.mov", "c.jpg", "d.txt"):
        (tmp_path / name).write_bytes(b"x")
    assert [p.rsplit("/", 1)[-1] for p in scan_folder(tmp_path)] == ["a.MP4", "b.mov", "c.jpg"]
    assert [p.rsplit("/", 1)[-1] for p in scan_folder(tmp_path, include_videos=False)] == ["c.jpg"]
    assert is_video_file("x.webm") and not is_video_file("x.png")
    assert media_kind("x.mkv") == "video" and media_kind("x.heic") == "image"


def test_probe(clip):
    info = probe_video(clip)
    assert (info.width, info.height) == (160, 120)
    assert 2.5 <= info.duration <= 3.5


def test_sample_frames_count_and_size(clip):
    frames = sample_frames(clip, count=4, max_side=100)
    assert len(frames) == 4
    assert all(f.media_type == "image/jpeg" for f in frames)
    assert all(max(f.width, f.height) <= 100 for f in frames)
    assert frames[0].data != frames[-1].data  # the test pattern moves, so frames differ


def test_probe_garbage_raises(tmp_path):
    bad = tmp_path / "bad.mp4"
    bad.write_bytes(b"definitely not a video")
    with pytest.raises(VideoError):
        probe_video(bad)


# ---- engines ---------------------------------------------------------------
def _response(text):
    return SimpleNamespace(content=[SimpleNamespace(type="text", text=text)], stop_reason="end_turn",
                           usage=SimpleNamespace(input_tokens=800, output_tokens=20))


class FakeMessages:
    def __init__(self, script):
        self.script = list(script)
        self.calls = []

    def create(self, **kwargs):
        self.calls.append(kwargs)
        return self.script.pop(0)


def test_api_engine_video_one_request_with_frames(clip, make_image):
    img = make_image("i.jpg", size=(50, 50))
    msgs = FakeMessages([_response('["pattern bars"]'), _response('["red square"]')])
    eng = ApiEngine(api_key="x", model="claude-haiku-5-5", client=SimpleNamespace(messages=msgs),
                    video_frames=3)
    res = {r.path: r for r in eng.describe([clip, img], RunControl())}
    assert res[clip].status == "ok" and res[clip].summary == "Video, 3s: pattern bars"
    assert res[img].status == "ok" and res[img].summary == "red square"
    assert len(msgs.calls) == 2
    video_call = msgs.calls[0]["messages"][0]["content"]
    assert len([b for b in video_call if b["type"] == "image"]) == 3
    assert "Frame 1 of 3" in video_call[0]["text"]
    assert "from one video" in video_call[-1]["text"]
    assert res[clip].input_tokens == 800


def test_api_engine_unreadable_video(tmp_path):
    bad = tmp_path / "bad.mov"
    bad.write_bytes(b"nope")
    msgs = FakeMessages([])
    eng = ApiEngine(api_key="x", model="claude-haiku-5-5", client=SimpleNamespace(messages=msgs))
    (r,) = eng.describe([str(bad)], RunControl())
    assert r.status == "unreadable" and msgs.calls == []


def test_cli_engine_rejects_videos(clip, tmp_path):
    eng = CliEngine(root=str(tmp_path), executable="/bin/true")
    (r,) = eng.describe([clip], RunControl())
    assert r.status == "error" and "API engine" in r.error


# ---- runner ------------------------------------------------------------------
def test_runner_hashes_and_dedupes_videos(clip, tmp_path):
    from image_cataloger.config import RunConfig
    from image_cataloger.runner import CatalogRunner

    folder = tmp_path / "media"
    folder.mkdir()
    shutil.copy(clip, folder / "clip.mp4")
    shutil.copy(clip, folder / "clip copy.mp4")
    base = tmp_path / "out" / "cat"
    cfg = RunConfig(folder=str(folder), dedupe_only=True, db_path=f"{base}.sqlite",
                    output_csv=f"{base}.csv", output_json=f"{base}.json")
    r = CatalogRunner(cfg, None, RunControl()).run()
    assert r.total == 2 and r.duplicates == 1 and r.pending == 1
    rows = {x["path"]: x for x in csv.DictReader(open(f"{base}.csv"))}
    canon = rows[str(folder / "clip.mp4")]
    assert canon["kind"] == "video" and canon["width"] == "160" and canon["duration_s"].startswith("3")
    assert rows[str(folder / "clip copy.mp4")]["duplicate_of"] == str(folder / "clip.mp4")

    cfg2 = RunConfig(folder=str(folder), include_videos=False, dedupe_only=True, db_path=f"{base}2.sqlite",
                     output_csv=f"{base}2.csv", output_json=f"{base}2.json")
    assert CatalogRunner(cfg2, None, RunControl()).run().total == 0
